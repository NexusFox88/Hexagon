import { readFile, writeFile } from 'node:fs/promises';

// Keep the Console design system tied to the portable, non-color token source.
const source = new URL('../asset/design-tokens/console-non-color.tokens.json', import.meta.url);
const { tokens } = JSON.parse(await readFile(source, 'utf8'));
const scope = ':root';
const declarations = Object.entries(tokens)
  .filter(([name]) => !name.startsWith('marketing.'))
  .map(([name, token]) => `  --console-${name.replaceAll('.', '-')}: ${token.value};`);
await writeFile(new URL('../apps/console/design-tokens.css', import.meta.url),
  `/* Generated by node tooling/generate-console-tokens.mjs. Do not edit values here. */\n${scope} {\n${declarations.join('\n')}\n}\n`);
